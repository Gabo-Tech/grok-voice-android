export function resolveLocale(tag: string): LocaleId {
  const norm = tag.trim().replace(/_/g, "-").toLowerCase();
  if (!norm) return "en";
  if (norm.includes("valencia")) return "ca-ES-valencia";
  if (norm.startsWith("es")) return "es";
  if (norm.startsWith("de")) return "de";
  if (norm.startsWith("pt")) return "pt";
  if (norm === "en" || norm.startsWith("en-")) return "en";
  return "en";
}

let current: LocaleId = typeof navigator === "undefined" ? "en" : resolveLocale(navigator.language);
const listeners = new Set<() => void>();

export function setAppLocale(tag: string) {
  const explicit = tag.trim();
  current = explicit ? resolveLocale(explicit) : resolveLocale(typeof navigator === "undefined" ? "en" : navigator.language);
  listeners.forEach((fn) => fn());
}

export function activeLocale(): LocaleId {
  return current;
}

export function translate(english: string): string {
  if (current === "en") return english;
  return catalogs[current][english] ?? english;
}

export function useT() {
  const [, setTick] = useState(0);
  useEffect(() => {
    const fn = () => setTick((n) => n + 1);
    listeners.add(fn);
    return () => {
      listeners.delete(fn);
    };
  }, []);
  return translate;
}
